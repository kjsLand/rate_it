/// The path of the generated bindings, from this crate's folder.
pub const BINDINGS_PATH: &str = "../ui/src/bindings.ts";

/// The header of the generated bindings file.
const BINDINGS_HEADER: &str = "// Generated by tauri-specta from the Rust commands. Do not edit.\n\
// Run `pnpm bindings` to make it again.\n";

/// The typed command list. The bindings in `ui/src/bindings.ts` come from it.
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .disable_serde_phases()
        .commands(collect_commands![
            ratings::now_playing,
            ratings::rate_current,
            ratings::recent_ratings,
            ratings::library_artists,
            ratings::library_tracks,
            ratings::rerate_track,
            ratings::track_history,
            discover::artist_details,
            discover::play_track,
            discover::build_playlist,
            discover::find_collaborators,
            discover::discover_playlist,
            discover::queue_current_album,
            discover::queue_my_top_ten,
            discover::cancel_task,
            share::song_card,
            share::album_card,
            share::cover_data_url,
            share::copy_card_image,
            account::account_status,
            account::save_client_id,
            account::sign_in,
            account::sign_out,
            transfer::import_legacy_file,
            transfer::import_ratings_file,
            transfer::export_ratings_file,
        ])
}

/// The TypeScript exporter with the project header.
pub fn typescript() -> Typescript {
    Typescript::default().header(BINDINGS_HEADER)
}

/// Starts the app.
pub fn run() {
    let builder = specta_builder();
    let result = tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_clipboard_manager::init())
        .plugin(tauri_plugin_deep_link::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let handle = app.handle().clone();
            let state = tauri::async_runtime::block_on(AppState::open(&handle))?;
            app.manage(state);
            #[cfg(mobile)]
            listen_for_sign_in(&handle);
            Ok(())
        })
        .run(tauri::generate_context!());
    if let Err(error) = result {
        // No window is open, so the log is the only place for this message.
        log_fatal(&error.to_string());
    }
}

#[expect(
    clippy::print_stderr,
    reason = "the app could not start: no window to show the error"
)]
fn log_fatal(message: &str) {
    eprintln!("rate_it could not start: {message}");
}

/// Mobile: the deep link `rateit://callback?...` finishes a sign-in.
#[cfg(mobile)]
fn listen_for_sign_in(handle: &tauri::AppHandle) {
    use tauri_plugin_deep_link::DeepLinkExt;

    let app = handle.clone();
    handle.deep_link().on_open_url(move |event| {
        for url in event.urls() {
            let app = app.clone();
            tauri::async_runtime::spawn(async move {
                let state = app.state::<AppState>();
                let ok = account::finish_mobile_sign_in(&state, url.as_str())
                    .await
                    .is_ok();
                let event = AccountChanged { signed_in: ok };
                // An error means that the window is closed: nothing listens.
                tauri_specta::Event::emit(&event, &app).ok();
            });
        }
    });
}

/// Sent to the screen when a mobile sign-in finishes.
#[cfg(mobile)]
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize, specta::Type, tauri_specta::Event)]
#[serde(rename_all = "camelCase")]
pub struct AccountChanged {
    pub signed_in: bool,
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The CI check of `docs/SPEC.md`: the committed bindings must equal a new generation.
    /// Set `UPDATE_BINDINGS=1` to write the file.
    #[test]
    fn bindings_are_current() {
        let fresh =
            std::env::temp_dir().join(format!("rate-it-bindings-{}.ts", std::process::id()));
        specta_builder().export(typescript(), &fresh).unwrap();
        let generated = std::fs::read_to_string(&fresh).unwrap();
        std::fs::remove_file(&fresh).unwrap();
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(BINDINGS_PATH);
        if std::env::var_os("UPDATE_BINDINGS").is_some() {
            std::fs::write(&path, &generated).unwrap();
        }
        let committed = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            committed == generated,
            "ui/src/bindings.ts is not current. Run `pnpm bindings` and commit the result."
        );
    }
}
